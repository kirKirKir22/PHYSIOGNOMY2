package com.kirill.physiognomy2.data

import androidx.compose.runtime.Immutable

enum class EyeShape { Almond, Round, Narrow, Drooping, Raised }

enum class Section(val title: String, val firstStep: Int, val lastStep: Int) {
    FaceTraits("Чтение черт лица", 1, 16),
    ExtraElements("Дополнительные элементы лица", 17, 19),
    FaceTypes("Общие формы и типы лица", 20, 26),
}

@Immutable
data class AnswerOption(
    val id: String,
    val label: String,
    val traits: List<String>,
    val description: String,
    val eyeShape: EyeShape? = null,
)

@Immutable
data class Question(
    val id: String,
    val title: String,
    val options: List<AnswerOption>,
)

@Immutable
data class Step(
    val number: Int,
    val title: String,
    val subtitle: String,
    val questions: List<Question>,
) {
    val id: String get() = "step$number"
}

private data class OptionSpec(
    val label: String,
    val traits: String,
    val description: String,
    val eyeShape: EyeShape? = null,
)

private data class QuestionSpec(val title: String, val options: List<OptionSpec>)

private fun o(
    label: String,
    traits: String,
    description: String,
    eyeShape: EyeShape? = null,
): OptionSpec = OptionSpec(label, traits, description, eyeShape)

private fun q(title: String, vararg options: OptionSpec) = QuestionSpec(title, options.toList())

private fun step(
    number: Int,
    title: String,
    subtitle: String,
    vararg specs: QuestionSpec,
): Step {
    val questions = specs.mapIndexed { index, spec ->
        val questionId = "s${number}q${index + 1}"
        Question(
            id = questionId,
            title = spec.title,
            options = spec.options.mapIndexed { optionIndex, option ->
                AnswerOption(
                    id = "$questionId-$optionIndex",
                    label = option.label,
                    traits = option.traits.split(';').map { it.trim() }.filter { it.isNotEmpty() },
                    description = option.description,
                    eyeShape = option.eyeShape,
                )
            },
        )
    }
    return Step(number, title, subtitle, questions)
}

