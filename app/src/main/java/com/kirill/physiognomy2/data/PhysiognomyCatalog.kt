    val totalQuestions: Int = steps.sumOf { it.questions.size }

    val totalOptions: Int = steps.sumOf { step -> step.questions.sumOf { it.options.size } }

    private val questionsById: Map<String, Question> =
        steps.flatMap { it.questions }.associateBy { it.id }

    private val stepByNumber: Map<Int, Step> = steps.associateBy { it.number }

    fun step(number: Int): Step = stepByNumber[number] ?: steps.first()

    fun question(id: String): Question? = questionsById[id]

    fun stepOf(questionId: String): Step? {
        val number = questionId.substringAfter("s").substringBefore("q").toIntOrNull() ?: return null
        return stepByNumber[number]
    }

    fun optionLabel(questionId: String, optionId: String): String? =
        questionsById[questionId]?.options?.firstOrNull { it.id == optionId }?.label

    fun questionTitle(questionId: String): String? = questionsById[questionId]?.title

    fun optionLabelById(optionId: String): String? {
        val questionId = optionId.substringBeforeLast('-')
        return optionLabel(questionId, optionId)
    }
}
