    fun areaFor(stepNumber: Int): ReadingArea? =
        ReadingArea.entries.firstOrNull { stepNumber in it.stepNumbers }

    fun areaTitleFor(stepNumber: Int): String = areaFor(stepNumber)?.title.orEmpty()

    fun termsFor(stepNumber: Int, questionId: String? = null): List<String> {
        if (questionId != null) {
            questionTerms[questionId]?.let { return it }
        }
        return stepTerms[stepNumber].orEmpty()
    }

    fun readingFor(stepNumber: Int, questionId: String? = null): String =
        termsFor(stepNumber, questionId).joinToString(", ")

    fun shortReadingFor(stepNumber: Int, questionId: String? = null, limit: Int = 3): String {
        val terms = termsFor(stepNumber, questionId)
        if (terms.size <= limit) return terms.joinToString(", ")
        return terms.take(limit).joinToString(", ") + "…"
    }

    fun isUnverified(questionId: String?): Boolean =
        questionId != null && questionId in unverifiedQuestions
